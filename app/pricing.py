"""Правила расчёта цены книги.

Зачем отдельным файлом: цену считает и страница цен, и форма заказа — правила должны быть
одни. Как со статусами заказа: один список, иначе цифры на разных страницах разъезжаются.

Как считается: базовый формат даёт цену, каждая страница сверх включённых добавляет свою цену.
Числа — за владельцем, здесь только место, где они живут в одном экземпляре.
"""
from __future__ import annotations

# Форматы: ключ, название, что входит в цену, добавка за страницу сверх включённых.
FORMATS = [
    {"key": "a4", "name": "А4, мягкая обложка", "base": 2000, "pages": 16, "per_page": 120},
    {"key": "a4_hard", "name": "А4, твёрдая обложка", "base": 2600, "pages": 16, "per_page": 130},
    {"key": "a4_soft", "name": "А4, премиум-бумага", "base": 3200, "pages": 16, "per_page": 150},
]

# Больше страниц — дороже, но не бесконечно: скидка на объём начинается с этого числа.
LONG_BOOK_PAGES = 40
MAX_PAGES = 80


def calc(format_key: str, pages: int) -> dict:
    """Посчитать вилку цены. Возвращает цену и подпись, почему столько."""
    f = next((x for x in FORMATS if x["key"] == format_key), FORMATS[0])
    # Ниже четырёх страниц книги не бывает, выше восьмидесяти — это уже не книга.
    pages = min(max(int(pages or 0), 4), MAX_PAGES)
    extra = max(0, pages - f["pages"])
    total = f["base"] + extra * f["per_page"]
    return {
        "format": f["name"],
        "pages": pages,
        "included": f["pages"],
        "total": total,
        "formatted": f"{round(total, -2):,.0f}".replace(",", " "),
        "long_book": pages >= LONG_BOOK_PAGES,
    }
