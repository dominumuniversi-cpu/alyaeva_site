"""Точки подключения модуля к сайту. По умолчанию — заглушки, которые говорят «не подключено».

Сайт подменяет их при установке (см. app/content_factory_glue.py):
    hooks.admin = ...   # (request) -> (пользователь, ответ-отказ)
    hooks.render = ...  # (request, шаблон, **контекст) -> ответ FastAPI

Заглушки нужны, чтобы модуль поднимался на «чистой машине» для него самого:
без сайта страница честно скажет, что её не подключили, а не упадёт с ImportError.
"""
from __future__ import annotations


def _no_admin(request):
    """Нет хука прав — значит и прав нет. Лучше отказать, чем пустить куда угодно."""
    return None, {"ok": False, "error": "Модуль не подключён к сайту: нет проверки прав"}


def _no_render(request, name: str, **kw):
    """Нет хука отрисовки — отвечаем текстом: страница без оболочки сайта ещё видна, а 500 — нет."""
    from fastapi.responses import HTMLResponse
    return HTMLResponse("<h1>Контент-завод</h1><p>Модуль не подключён к сайту: нет отрисовки страницы.</p>")


admin = _no_admin
render = _no_render
